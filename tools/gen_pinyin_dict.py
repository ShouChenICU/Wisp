#!/usr/bin/env python3
"""Generates components/wisp_ui/src/pinyin_dict.cpp, the pinyin dictionary
of the system keyboard (wisp/ui/system_layer.hpp).

The source is LVGL's own default dictionary (`lv_ime_pinyin_def_dict` in
src/widgets/ime/lv_ime_pinyin.c, MIT License), read from the LVGL source
tree the build already fetched -- nothing is downloaded. Its candidates
include traditional and Japanese forms the built-in CJK font
(lv_font_cjk_16, tools/gen_cjk_font.py) has no glyph for, so only the
candidates in the font's character set are kept: the keyboard reuses the
existing font instead of growing it. Entries left without candidates are
dropped, a candidate listed twice in one entry is kept once (first
place), and the entries are sorted by pinyin, which LVGL's IME needs for
its per-letter index and its prefix search.

The LVGL version must be the pinned one (cmake/wisp_host_deps.cmake,
firmware/main/idf_component.yml), so the output only changes when the
pin, the font's character set or this script does.

Usage:
  gen_pinyin_dict.py [--lvgl <LVGL source dir>]          # write the file
  gen_pinyin_dict.py [--lvgl <LVGL source dir>] --check  # fail if stale
Without --lvgl the script looks in build/sim/_deps/lvgl-src (the
simulator's FetchContent checkout) and firmware/managed_components/
lvgl__lvgl (the component manager's).
"""

import argparse
import pathlib
import re
import sys

TOOLS = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))

import gen_cjk_font  # noqa: E402

ROOT = TOOLS.parent
OUTPUT = ROOT / "components/wisp_ui/src/pinyin_dict.cpp"
LVGL_VERSION = (9, 5, 0)
LVGL_CANDIDATES = [
    ROOT / "build/sim/_deps/lvgl-src",
    ROOT / "firmware/managed_components/lvgl__lvgl",
]
IME_SOURCE = "src/widgets/ime/lv_ime_pinyin.c"

_ENTRY = re.compile(r'\{\s*"([a-z]+)"\s*,\s*"([^"\\]*)"\s*\}')


def lvgl_version(root):
    text = (root / "lv_version.h").read_text(encoding="utf-8")
    parts = []
    for name in ("MAJOR", "MINOR", "PATCH"):
        m = re.search(rf"#define\s+LVGL_VERSION_{name}\s+(\d+)", text)
        if m is None:
            return None
        parts.append(int(m.group(1)))
    return tuple(parts)


def find_lvgl(explicit):
    candidates = [explicit] if explicit is not None else LVGL_CANDIDATES
    pinned = ".".join(map(str, LVGL_VERSION))
    for root in candidates:
        if not (root / IME_SOURCE).is_file() or not (root / "lv_version.h").is_file():
            continue
        version = lvgl_version(root)
        if version != LVGL_VERSION:
            found = ".".join(map(str, version)) if version else "unknown"
            sys.exit(f"error: {root} is LVGL {found}, expected the pinned {pinned}")
        return root
    where = str(explicit) if explicit is not None else " or ".join(str(c) for c in LVGL_CANDIDATES)
    sys.exit(
        f"error: no LVGL {pinned} source in {where}; configure the simulator first "
        "(cmake -S simulator -B build/sim -G Ninja) or pass --lvgl"
    )


def default_dict(lvgl_root):
    """LVGL's default dictionary as a list of (pinyin, candidates)."""
    text = (lvgl_root / IME_SOURCE).read_text(encoding="utf-8")
    start = text.find("lv_ime_pinyin_def_dict[] = {")
    end = text.find("{NULL, NULL}", start)
    if start < 0 or end < 0:
        sys.exit(f"error: lv_ime_pinyin_def_dict not found in {lvgl_root / IME_SOURCE}")
    entries = _ENTRY.findall(text[start:end])
    if not entries:
        sys.exit("error: lv_ime_pinyin_def_dict has no entries")
    return entries


def filter_dict(entries, charset):
    """Keeps the candidates in `charset`, once each, and the entries that
    still have one, sorted by pinyin."""
    merged = {}
    for py, cands in entries:
        kept = merged.setdefault(py, [])
        for c in cands:
            if c in charset and c not in kept:
                kept.append(c)
    out = []
    for py in sorted(merged):
        cands = "".join(merged[py])
        if not cands:
            continue
        for c in cands:
            # The IME steps through candidates three UTF-8 bytes at a time.
            if len(c.encode("utf-8")) != 3:
                sys.exit(f"error: candidate {c!r} of {py!r} is not a 3-byte UTF-8 character")
        out.append((py, cands))
    return out


def render(entries):
    lines = [
        "// Generated by tools/gen_pinyin_dict.py -- do not edit; run the script.",
        "//",
        "// LVGL " + ".".join(map(str, LVGL_VERSION)) + "'s default pinyin dictionary",
        "// (lv_ime_pinyin_def_dict in src/widgets/ime/lv_ime_pinyin.c; MIT License,",
        "// see THIRD_PARTY_NOTICES.md) with only the candidates lv_font_cjk_16 has,",
        "// sorted by pinyin. A constant table, so it stays in flash.",
        "",
        '#include "wisp/ui/system_layer.hpp"',
        "",
        "namespace wisp::ui::detail {",
        "",
        "namespace {",
        "",
        "const lv_pinyin_dict_t kPinyinDict[] = {",
    ]
    lines += [f'    {{"{py}", "{cands}"}},' for py, cands in entries]
    lines += [
        "    {nullptr, nullptr},",
        "};",
        "",
        "}  // namespace",
        "",
        "const lv_pinyin_dict_t* pinyin_dict() { return kPinyinDict; }",
        "",
        "}  // namespace wisp::ui::detail",
        "",
    ]
    return "\n".join(lines)


def generate(lvgl_root):
    chars, _ = gen_cjk_font.build_charset()
    return render(filter_dict(default_dict(lvgl_root), set(chars)))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--lvgl", type=pathlib.Path, help="LVGL source directory")
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args(argv)

    text = generate(find_lvgl(args.lvgl))
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(
                f"error: {OUTPUT.relative_to(ROOT)} is stale; run python3 tools/gen_pinyin_dict.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date", file=sys.stderr)
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
