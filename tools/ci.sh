#!/usr/bin/env bash
# Daily CI: repository checks, host build, unit tests and core smoke paths.
# Use --full for all tool self-tests and simulator scenarios before release.
# WISP_CI_BASE optionally selects tool self-tests from a Git comparison;
# without a usable baseline all tool self-tests run.
#
# Note: this only checks formatting (clang-format --dry-run --Werror);
# it does not reformat anything. Run `clang-format -i` yourself first
# if this fails because of formatting drift.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

FULL=OFF
SELECT_ARGS=()
case "${1:-}" in
    "") ;;
    --full) FULL=ON; SELECT_ARGS+=(--full) ;;
    *) echo "usage: bash tools/ci.sh [--full]" >&2; exit 2 ;;
esac
if (( $# > 1 )); then
    echo "usage: bash tools/ci.sh [--full]" >&2
    exit 2
fi
if [[ -n "${WISP_CI_BASE:-}" ]]; then
    SELECT_ARGS+=(--base "$WISP_CI_BASE")
fi
python3 tools/ci_tool_tests_test.py
SELECTED_TOOL_TESTS="$(python3 tools/ci_tool_tests.py "${SELECT_ARGS[@]}")"
run_tool_test() {
    if grep -Fxq "$1" <<< "$SELECTED_TOOL_TESTS"; then
        echo "==> tools/$1.py"
        python3 "tools/$1.py"
    else
        echo "==> skip tools/$1.py (tool and inputs unchanged)"
    fi
}

# The clang-format version this repo is formatted against -- this is
# the single place that version is recorded:
# .github/workflows/ci.yml's "Install pinned clang-format" step reads
# this exact line (by grep) to install the matching PyPI package,
# rather than duplicating the literal. Different clang-format major
# versions format the same source differently, so a mismatch here (a
# locally installed clang-format from apt/brew/etc. that isn't this
# one) can make --dry-run --Werror below disagree with CI -- warn,
# don't fail, since the actual authority is whatever CI has pinned.
CLANG_FORMAT_VERSION="23.1.3"

CLANG_FORMAT_ACTUAL="$(clang-format --version | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1)"
echo "==> clang-format --version: ${CLANG_FORMAT_ACTUAL} (pinned: ${CLANG_FORMAT_VERSION})"
if [[ "${CLANG_FORMAT_ACTUAL%%.*}" != "${CLANG_FORMAT_VERSION%%.*}" ]]; then
    echo "warning: clang-format major version differs from the pin (${CLANG_FORMAT_ACTUAL} vs ${CLANG_FORMAT_VERSION});" \
         "formatting here may disagree with CI" >&2
fi

# Every C/C++ source file in the repo, except build output,
# components/wisp_ui/fonts/ (generated font data -- see
# tools/gen_cjk_font.py / docs/references.md), hidden agent/tool state
# (.claude/, .playwright-mcp/, .superpowers/, which may contain independent
# worktrees or scratch sources),
# firmware/build/, firmware/build-*/ and firmware/managed_components/ (ESP-IDF build
# output and third-party sources fetched by the component manager --
# both gitignored, neither ours to format), and
# firmware/components/gen_bmgr_codes/ (generated by `idf.py bmgr`,
# gitignored), and third_party/ (upstream sources vendored verbatim,
# e.g. Lua by tools/vendor_lua.sh -- never reformatted).
mapfile -t SOURCE_FILES < <(find . \
    \( -path './build' -o -path './.git' -o -path './.claude' \
       -o -path './.playwright-mcp' -o -path './.superpowers' \
       -o -path './components/wisp_ui/fonts' \
       -o -path './firmware/build' -o -path './firmware/build-*' \
       -o -path './firmware/managed_components' \
       -o -path './firmware/components/gen_bmgr_codes' -o -path './third_party' \) -prune -o \
    -type f \( -name '*.hpp' -o -name '*.cpp' -o -name '*.h' -o -name '*.c' \) -print)

echo "==> clang-format --dry-run --Werror (${#SOURCE_FILES[@]} files)"
clang-format --dry-run --Werror "${SOURCE_FILES[@]}"

# sdkconfig.defaults is a Kconfig fragment, not C/C++: kconfgen silently
# ignores malformed lines (e.g. "CONFIG_X = y"), dropping the setting.
echo "==> firmware/sdkconfig.defaults line format"
if grep -vnE '^(#.*|CONFIG_[A-Z0-9_]+=.*)?$' firmware/sdkconfig.defaults; then
    echo "error: malformed lines in firmware/sdkconfig.defaults (see above)" >&2
    exit 1
fi

# AGENTS.md section 5: comments/docs must explain why the code is the
# way it is, not which review round changed it -- that history belongs
# in commit messages. Scans the directories/files that hold Wisp's own
# code and docs (not docs/superpowers/, which is the spec/plan archive
# and legitimately full of round-by-round history) for two symptoms:
# references to files under the gitignored .superpowers/ directory
# (dead links on a fresh checkout, since those files are never
# committed), and review/round markers -- both spelled-out phrases
# ("Fix round N", "Re-review N", "review round N", "round N, item M",
# "(final review)") and bare finding IDs (a letter from
# I/M/N/C immediately followed by digits, immediately followed by ':'
# or wrapped alone in parens, e.g. "N3:" or "(M8)") -- narrow enough
# that a real identifier like "I2C" or an unrelated "(I1)" sharing the
# same shape (see lv_conf.h's color-depth comment, excluded below)
# doesn't trip it.
echo "==> process-history / review-marker guard (AGENTS.md section 5)"
# --exclude=ci.sh: this very script has to spell out the strings above
# to document what it's checking for, so it would otherwise flag
# itself. --exclude=AGENTS.md: section 5 itself quotes these same
# patterns as examples of what's forbidden (using a literal "N" rather
# than a digit, so none of the *other* patterns below ever match it
# either -- deliberately, so this exclusion only needs to cover the
# bare-ID examples). --exclude=lv_conf.h: LVGL's own color-depth
# comment ("1 (I1), 8 (L8), ...") is the one real identifier in this
# tree shaped like a bare finding ID.
GUARD_MATCHES="$(grep -rnE \
    '\.superpowers/|task-[0-9a-zA-Z]+-(brief|report|review)\.md|global-constraints\.md|[Ff]ix round|[Rr]e-review|[Rr]eview round|\bround [0-9]+, item|\bR2-[0-9]|\bTask [0-9]+[a-z]?\b|\((final review|[CIMN][0-9]+)\)|\b[CIMN][0-9]+:' \
    --include='*.cpp' --include='*.hpp' --include='*.h' --include='*.c' \
    --include='*.md' --include='*.yaml' --include='*.yml' --include='*.py' \
    --include='CMakeLists.txt' --include='*.cmake' --include='*.sh' \
    --include='sdkconfig.defaults*' --include='*.S' \
    --exclude='ci.sh' --exclude='AGENTS.md' --exclude='lv_conf.h' \
    components boards drivers firmware/main firmware/sdkconfig.defaults \
    firmware/CMakeLists.txt simulator tests tools docs cmake .github *.md \
    2>/dev/null | grep -v '^docs/superpowers/' || true)"
if [[ -n "$GUARD_MATCHES" ]]; then
    echo "$GUARD_MATCHES"
    echo "error: process-history or review-marker reference found above -- strip it," \
         "keeping only the technical rationale (AGENTS.md section 5)" >&2
    exit 1
fi

run_tool_test check_layering_test

echo "==> tools/check_layering.py"
python3 tools/check_layering.py

run_tool_test pack_assets_test

# The scene push tool (scene-runtime-core spec 7.3), against a fake device
# served from the test itself.
run_tool_test wisp_scene_test

# The admin web UI must fit its gzip budget (spec 7.1) and reference only
# files inside the pack. The pack written here is a throwaway; the
# simulator and firmware builds pack web/ themselves.
echo "==> tools/pack_assets.py web --budget-kb 170"
python3 tools/pack_assets.py web -o build/ci/web-budget.wpak --budget-kb 170

# The admin UI's zh/ja/en dictionaries must carry identical key sets
# (spec 7.4).
run_tool_test check_i18n_test

echo "==> tools/check_i18n.py"
python3 tools/check_i18n.py

# The committed CJK font must match tools/gen_cjk_font.py's character set
# (including every character the device UI string tables use; spec 8.3).
run_tool_test gen_cjk_font_test

# The committed vector (TrueType) font subset must be a hinting-free
# glyf font whose cmap matches tools/gen_vector_font.py's character set
# (spec 3.1).
run_tool_test gen_vector_font_test

# The fonts partition image: header layout, reproducibility, and the
# committed font fitting the reference board's partition (spec 3.2).
run_tool_test pack_font_image_test

# The glyphs partition image: header and section layout, reproducibility,
# and that it reproduces the committed CJK body font exactly (glyph-partition
# spec 3.1).
run_tool_test pack_glyph_image_test

# docs.read's compiled-in topics must be what tools/gen_agent_docs.py
# makes of docs/scene-api.md and scenes/examples (agent-core spec 4.4).
run_tool_test gen_agent_docs_test
echo "==> tools/gen_agent_docs.py --check"
python3 tools/gen_agent_docs.py --check

echo "==> cmake -S simulator -B build/sim -G Ninja"
cmake -S simulator -B build/sim -G Ninja -DWISP_FULL_SMOKE="$FULL"

# The keyboard's pinyin dictionary must be what tools/gen_pinyin_dict.py
# makes of the pinned LVGL's default one and the CJK font's character set.
# It reads the LVGL source the configure step above fetched; nothing is
# downloaded.
echo "==> tools/gen_pinyin_dict.py --check"
python3 tools/gen_pinyin_dict.py --check

# The committed icon fonts must hold exactly the pinned LVGL's LV_SYMBOL_*
# icons and the generator's Wisp icons, and wisp/ui/symbols.hpp must match
# the latter (vector-font spec 4.6). Reads the same LVGL source; offline.
run_tool_test gen_icon_font_test
echo "==> tools/gen_icon_font.py --check"
python3 tools/gen_icon_font.py --check

echo "==> cmake --build build/sim"
cmake --build build/sim

echo "==> ctest --test-dir build/sim"
ctest --test-dir build/sim --output-on-failure
