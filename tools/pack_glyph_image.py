#!/usr/bin/env python3
"""Packs the 16 px body font (components/wisp_ui/fonts/lv_font_cjk_16.c,
generated by lv_font_conv via tools/gen_cjk_font.py) into the image the
`glyphs` partition holds (glyph-partition spec 3.1). The packer parses the
generated C arrays with regular expressions -- it never compiles or links
the `.c` file -- and re-emits their data in a fixed, portable layout that a
C++ reader can validate and map without pulling in LVGL's bitfield-packed
`lv_font_fmt_txt_glyph_dsc_t`. Everything is little-endian, with no padding
between fields or sections, and every offset is a byte offset from the
start of the payload (the first byte after the header).

Header (32 bytes, same layout as `fonts.bin`, see pack_font_image.py):

  offset 0   4 bytes  magic b"WGLY"
  offset 4   u16      format version, 1
  offset 6   u16      header length, 32 (the payload starts here)
  offset 8   u32      payload length in bytes
  offset 12  u32      CRC-32 of the payload (zlib.crc32, same as wisp::crc32)
  offset 16  16 bytes reserved, zero

Payload, in order:

  metrics (32 bytes): u16 line_height, i16 base_line, i8 underline_position,
    i8 underline_thickness, u8 bpp (4), u8 reserved 0, u16 kern_scale,
    u16 cmap_count, u32 glyph_count (including reserved glyph id 0),
    u32 list_bytes, u32 kern_pair_count, u32 bitmap_bytes, u32 reserved 0.

  glyphs: glyph_count entries of 10 bytes each, one per glyph_dsc[] entry
    including the unused id 0: u32 bitmap_index, u16 adv_w, u8 box_w,
    u8 box_h, i8 ofs_x, i8 ofs_y. bitmap_index is an offset into the
    bitmap section (not the payload), exactly as LVGL's glyph_dsc stores
    it -- the renderer adds it to the bitmap section's own base pointer.

  cmaps: cmap_count entries of 20 bytes each, one per cmaps[] entry:
    u32 range_start, u16 range_length, u16 glyph_id_start, u8 type
    (the lv_font_fmt_txt_cmap_type_t value: FORMAT0_FULL=0, SPARSE_FULL=1,
    FORMAT0_TINY=2, SPARSE_TINY=3), u8 reserved 0, u16 list_length,
    u32 unicode_list_offset, u32 glyph_id_ofs_offset. The two offsets are
    byte offsets from the start of the payload into the lists section
    below, or 0xFFFFFFFF when that cmap has no such list (FORMAT0_TINY
    has neither, FORMAT0_FULL has only glyph_id_ofs_list, SPARSE_TINY has
    only unicode_list). SPARSE_FULL would need both and is not supported
    (see below) -- the committed font has none, so that case is rejected
    outright rather than carried as untested code.

  lists (list_bytes): each cmap's unicode_list (u16 per entry, only for
    SPARSE_TINY) or glyph_id_ofs_list (u8 per entry, only for
    FORMAT0_FULL) concatenated in cmap order.

  kern (kern_pair_count * 5 bytes): kern_pair_count glyph-id pairs
    (u16 left, u16 right) followed by kern_pair_count i8 values, scaled
    by the metrics' kern_scale (12.4 format, as in LVGL). Only the
    `kern_pairs` form is supported (`glyph_ids_size == 1`, 16-bit ids,
    no kern classes) -- the committed font uses exactly this form.

  bitmap (bitmap_bytes): identical, byte for byte, to glyph_bitmap[].

Fails with a non-zero exit and a message on stderr when the source has
kern classes, a kern_pairs array with a glyph id width other than 16 bits,
a bitmap format other than LV_FONT_FMT_TXT_PLAIN (uncompressed) -- the
glyphs partition reader only ever reads raw bitmap bytes -- a SPARSE_FULL
cmap (needs both a unicode_list and a glyph_id_ofs_list; not implemented,
since the committed font has none), a glyph whose bitmap_index or adv_w
does not fit LVGL's bitfields or whose bitmap_index is not inside
glyph_bitmap[] (the device's reader refuses the same), or when the image is larger than
--max-bytes (the glyphs partition's size).

Usage: pack_glyph_image.py <lv_font_c> -o <out> [--max-bytes N]
"""

import argparse
import math
import pathlib
import re
import struct
import sys
import zlib

MAGIC = b"WGLY"
VERSION = 1
HEADER = struct.Struct("<4sHHII16x")

METRICS = struct.Struct("<HhbbBBHHIIIII")
GLYPH = struct.Struct("<IHBBbb")
CMAP = struct.Struct("<IHHBBHII")

NO_OFFSET = 0xFFFFFFFF

# Widths of the lv_font_fmt_txt_glyph_dsc_t bitfields the reader stores
# these in (LV_FONT_FMT_TXT_LARGE 0).
MAX_BITMAP_INDEX = 2**20 - 1
MAX_ADV_W = 2**12 - 1

CMAP_TYPE_VALUES = {
    "LV_FONT_FMT_TXT_CMAP_FORMAT0_FULL": 0,
    "LV_FONT_FMT_TXT_CMAP_SPARSE_FULL": 1,
    "LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY": 2,
    "LV_FONT_FMT_TXT_CMAP_SPARSE_TINY": 3,
}


class PackError(Exception):
    pass


def _find_block(text, open_pattern):
    """Returns the text between the `{` that `open_pattern` ends at and the
    next top-level `};`. Nested struct entries in these arrays close with
    `},`, never `};`, so the first `\n};` after the opening brace is always
    the end of the array itself."""
    m = re.search(open_pattern, text)
    if not m:
        raise PackError(f"could not find pattern: {open_pattern}")
    end = text.find("\n};", m.end())
    if end < 0:
        raise PackError(f"unterminated array after: {open_pattern}")
    return text[m.end() : end]


def _scalar(text, field, pattern=r"-?\d+"):
    m = re.search(rf"\.{field}\s*=\s*({pattern})", text)
    if not m:
        raise PackError(f"could not find field .{field}")
    return int(m.group(1))


def _strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def _parse_glyph_bitmap(text):
    body = _find_block(text, r"glyph_bitmap\[\]\s*=\s*\{")
    tokens = re.findall(r"0[xX][0-9a-fA-F]+", _strip_comments(body))
    return bytes(int(t, 16) for t in tokens)


def _parse_glyph_dsc(text):
    body = _find_block(text, r"\bglyph_dsc\[\]\s*=\s*\{")
    entries = re.findall(
        r"\{\s*\.bitmap_index\s*=\s*(\d+),\s*\.adv_w\s*=\s*(\d+),\s*"
        r"\.box_w\s*=\s*(\d+),\s*\.box_h\s*=\s*(\d+),\s*"
        r"\.ofs_x\s*=\s*(-?\d+),\s*\.ofs_y\s*=\s*(-?\d+)\s*\}",
        body,
    )
    if not entries:
        raise PackError("glyph_dsc[] has no entries")
    return [tuple(int(v) for v in e) for e in entries]


def _parse_named_arrays(text):
    """Returns {array name: (element width in bytes, values)} for every
    unicode_list_N and glyph_id_ofs_list_N array. The width comes from the
    C type lv_font_conv declared the array with: callers use it to check
    each array is the width its cmap type requires (unicode_list always
    16-bit, glyph_id_ofs_list 8-bit for the only supported form,
    FORMAT0_FULL -- see lv_font_fmt_txt.h's comment on `glyph_id_ofs_list`
    for the 16-bit SPARSE_FULL form this packer rejects)."""
    arrays = {}
    pattern = re.compile(
        r"static const (uint8_t|uint16_t)\s+"
        r"((?:unicode_list|glyph_id_ofs_list)_\d+)\[\]\s*=\s*\{(.*?)\n\};",
        re.S,
    )
    for type_name, name, body in pattern.findall(text):
        width = 1 if type_name == "uint8_t" else 2
        values = [int(t, 0) for t in re.findall(r"0[xX][0-9a-fA-F]+|\d+", body)]
        arrays[name] = (width, values)
    return arrays


def _parse_cmaps(text):
    body = _find_block(text, r"cmaps\[\]\s*=\s*\{")
    entries = re.findall(
        r"\{\s*\.range_start\s*=\s*(\d+),\s*\.range_length\s*=\s*(\d+),\s*"
        r"\.glyph_id_start\s*=\s*(\d+),\s*"
        r"\.unicode_list\s*=\s*(\w+),\s*\.glyph_id_ofs_list\s*=\s*(\w+),\s*"
        r"\.list_length\s*=\s*(\d+),\s*\.type\s*=\s*(LV_FONT_FMT_TXT_CMAP_\w+)\s*\}",
        body,
    )
    if not entries:
        raise PackError("cmaps[] has no entries")
    parsed = []
    for range_start, range_length, glyph_id_start, unicode_list, glyph_id_ofs_list, list_length, type_name in entries:
        if type_name not in CMAP_TYPE_VALUES:
            raise PackError(f"unknown cmap type {type_name}")
        parsed.append(
            {
                "range_start": int(range_start),
                "range_length": int(range_length),
                "glyph_id_start": int(glyph_id_start),
                "unicode_list": unicode_list,
                "glyph_id_ofs_list": glyph_id_ofs_list,
                "list_length": int(list_length),
                "type": type_name,
            }
        )
    return parsed


def _parse_kern(text):
    ids_body = _find_block(text, r"kern_pair_glyph_ids\[\]\s*=\s*\{")
    ids = [int(t) for t in re.findall(r"\d+", ids_body)]
    values_body = _find_block(text, r"kern_pair_values\[\]\s*=\s*\{")
    values = [int(t) for t in re.findall(r"-?\d+", values_body)]
    pair_cnt = _scalar(text, "pair_cnt")
    glyph_ids_size = _scalar(text, "glyph_ids_size")
    if len(ids) != pair_cnt * 2:
        raise PackError(f"kern_pair_glyph_ids has {len(ids)} entries, expected {pair_cnt * 2}")
    if len(values) != pair_cnt:
        raise PackError(f"kern_pair_values has {len(values)} entries, expected {pair_cnt}")
    pairs = list(zip(ids[0::2], ids[1::2]))
    return pairs, values, glyph_ids_size


def pack(c_source_text):
    """Returns the glyphs partition image for the LVGL font literally in
    `c_source_text` (the text of a file like lv_font_cjk_16.c); raises
    PackError when it uses a form of kern or bitmap data the glyphs
    partition reader cannot map."""
    kern_classes = _scalar(c_source_text, "kern_classes")
    if kern_classes != 0:
        raise PackError("kern classes are not supported; only kern_pairs (glyph_ids_size=1) can be packed")
    bitmap_format = _scalar(c_source_text, "bitmap_format")
    if bitmap_format != 0:
        raise PackError(f"bitmap_format {bitmap_format} is not supported; only LV_FONT_FMT_TXT_PLAIN (0) can be mapped from flash")
    bpp = _scalar(c_source_text, "bpp")
    kern_scale = _scalar(c_source_text, "kern_scale")
    cmap_num = _scalar(c_source_text, "cmap_num")

    line_height = _scalar(c_source_text, "line_height")
    base_line = _scalar(c_source_text, "base_line")
    underline_position = _scalar(c_source_text, "underline_position")
    underline_thickness = _scalar(c_source_text, "underline_thickness")

    bitmap_bytes_data = _parse_glyph_bitmap(c_source_text)
    glyphs = _parse_glyph_dsc(c_source_text)
    cmaps = _parse_cmaps(c_source_text)
    if len(cmaps) != cmap_num:
        raise PackError(f"cmaps[] has {len(cmaps)} entries, font_dsc.cmap_num says {cmap_num}")
    for cmap in cmaps:
        if cmap["type"] == "LV_FONT_FMT_TXT_CMAP_SPARSE_FULL":
            raise PackError(
                "SPARSE_FULL cmaps are not supported; only FORMAT0_FULL, FORMAT0_TINY and SPARSE_TINY can be packed"
            )
    named_arrays = _parse_named_arrays(c_source_text)
    kern_pairs, kern_values, glyph_ids_size = _parse_kern(c_source_text)
    if glyph_ids_size != 1:
        raise PackError(f"kern_pairs.glyph_ids_size={glyph_ids_size} is not supported; only 16-bit glyph ids can be packed")

    glyph_count = len(glyphs)
    for left, right in kern_pairs:
        if left >= glyph_count or right >= glyph_count:
            raise PackError(f"kern pair ({left}, {right}) references a glyph id past glyph_count={glyph_count}")

    for index, (bitmap_index, adv_w, box_w, box_h, ofs_x, ofs_y) in enumerate(glyphs):
        # The same limits open_glyph_image() (components/wisp_ui/src/
        # glyph_image.cpp) enforces, so a font the device would refuse
        # fails the build instead.
        if bitmap_index > MAX_BITMAP_INDEX:
            raise PackError(f"glyph {index}'s bitmap_index {bitmap_index} does not fit LVGL's 20-bit field")
        if adv_w > MAX_ADV_W:
            raise PackError(f"glyph {index}'s adv_w {adv_w} does not fit LVGL's 12-bit field")
        # Even an empty glyph's index must name a byte of the bitmap: LVGL
        # hands out &glyph_bitmap[bitmap_index] for the raw bitmap.
        if bitmap_index >= len(bitmap_bytes_data):
            raise PackError(
                f"glyph {index}'s bitmap_index {bitmap_index} is past glyph_bitmap[] ({len(bitmap_bytes_data)} bytes)"
            )
        size = math.ceil(box_w * box_h * bpp / 8)
        if bitmap_index + size > len(bitmap_bytes_data):
            raise PackError(
                f"glyph {index}'s bitmap ends at {bitmap_index + size}, "
                f"past glyph_bitmap[] ({len(bitmap_bytes_data)} bytes)"
            )

    try:
        glyph_section = b"".join(GLYPH.pack(*g) for g in glyphs)
    except struct.error as e:
        raise PackError(f"a glyph_dsc entry does not fit the image's glyph record: {e}") from e

    base_lists_offset = METRICS.size + GLYPH.size * len(glyphs) + CMAP.size * len(cmaps)
    lists_section = bytearray()
    cmap_section = bytearray()
    for cmap in cmaps:
        # A cmap has at most one of these two lists: FORMAT0_TINY has
        # neither, FORMAT0_FULL only glyph_id_ofs_list, SPARSE_TINY only
        # unicode_list. SPARSE_FULL would need both, and is rejected above.
        unicode_list_offset = NO_OFFSET
        if cmap["unicode_list"] != "NULL":
            width, values = named_arrays.get(cmap["unicode_list"], (None, None))
            if width is None:
                raise PackError(f"could not find array {cmap['unicode_list']}")
            if width != 2:
                raise PackError(f"{cmap['unicode_list']} must be a 16-bit unicode_list")
            if len(values) != cmap["list_length"]:
                raise PackError(f"{cmap['unicode_list']} has {len(values)} entries, cmap says list_length={cmap['list_length']}")
            unicode_list_offset = base_lists_offset + len(lists_section)
            for v in values:
                lists_section += struct.pack("<H", v)

        glyph_id_ofs_offset = NO_OFFSET
        if cmap["glyph_id_ofs_list"] != "NULL":
            width, values = named_arrays.get(cmap["glyph_id_ofs_list"], (None, None))
            if width is None:
                raise PackError(f"could not find array {cmap['glyph_id_ofs_list']}")
            if width != 1:
                raise PackError(f"{cmap['glyph_id_ofs_list']} must be an 8-bit glyph_id_ofs_list (FORMAT0_FULL)")
            if len(values) != cmap["list_length"]:
                raise PackError(f"{cmap['glyph_id_ofs_list']} has {len(values)} entries, cmap says list_length={cmap['list_length']}")
            glyph_id_ofs_offset = base_lists_offset + len(lists_section)
            for v in values:
                lists_section += struct.pack("<B", v)

        cmap_section += CMAP.pack(
            cmap["range_start"],
            cmap["range_length"],
            cmap["glyph_id_start"],
            CMAP_TYPE_VALUES[cmap["type"]],
            0,
            cmap["list_length"],
            unicode_list_offset,
            glyph_id_ofs_offset,
        )

    kern_ids_section = b"".join(struct.pack("<HH", left, right) for left, right in kern_pairs)
    kern_values_section = struct.pack(f"<{len(kern_values)}b", *kern_values) if kern_values else b""

    metrics = METRICS.pack(
        line_height,
        base_line,
        underline_position,
        underline_thickness,
        bpp,
        0,
        kern_scale,
        len(cmaps),
        glyph_count,
        len(lists_section),
        len(kern_pairs),
        len(bitmap_bytes_data),
        0,
    )

    payload = (
        metrics
        + glyph_section
        + bytes(cmap_section)
        + bytes(lists_section)
        + kern_ids_section
        + kern_values_section
        + bitmap_bytes_data
    )
    header = HEADER.pack(MAGIC, VERSION, HEADER.size, len(payload), zlib.crc32(payload))
    return header + payload


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("lv_font_c", type=pathlib.Path)
    parser.add_argument("-o", "--output", type=pathlib.Path, required=True)
    # Decimal or 0x-prefixed: partition_table_get_partition_info() reports hex.
    parser.add_argument("--max-bytes", type=lambda s: int(s, 0), default=None)
    args = parser.parse_args(argv)

    try:
        image = pack(args.lv_font_c.read_text(encoding="utf-8"))
        if args.max_bytes is not None and len(image) > args.max_bytes:
            raise PackError(f"glyph image is {len(image)} bytes, the partition holds {args.max_bytes}")
    except PackError as e:
        print(f"pack_glyph_image: {e}", file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.output.with_name(args.output.name + ".tmp")
    tmp.write_bytes(image)
    tmp.replace(args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
