#!/usr/bin/env python3
"""Generates components/wisp_agent/src/docs_data.cpp, the docs.read topics
that come from files (agent-core spec 4.4):

- docs/scene-api.md is cut at its "## " headings: "## wisp.<m>..." goes to
  lua/<m> (every such section of one module, in document order), "## Screen
  shape" to screen, everything else (the intro included) to lua. A "### "
  heading stays with the section it is in; HTML comments are dropped.
- scenes/examples/<id>/ gives example/<id>: its scene.json, then every .lua
  file by path. "examples" lists the ids with their names.

The widget topics are built at run time from the schema (docs.cpp), so
they are not here.

Usage: python3 tools/gen_agent_docs.py [--check] [--doc F] [--examples D] [--output F]
--check compares instead of writing and fails when the output is stale.
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DELIM = "wispdoc"
END = ")" + DELIM + '"'

HEADER = """\
// Generated by tools/gen_agent_docs.py from docs/scene-api.md and
// scenes/examples; do not edit. tools/ci.sh fails when it is stale.

#include "docs_data.hpp"

namespace wisp::agent {

// clang-format off
constexpr DocEntry kDocEntries[] = {
"""

FOOTER = """\
};
// clang-format on

std::span<const DocEntry> doc_entries() { return kDocEntries; }

}  // namespace wisp::agent
"""


def split_doc(text):
    """{topic: text} from scene-api.md, topics in first-seen order."""
    text = re.sub(r"<!--.*?-->\n*", "", text, flags=re.S)
    sections = {"lua": []}
    current = "lua"
    for line in text.splitlines(keepends=True):
        if line.startswith("## "):
            title = line[3:].strip()
            m = re.match(r"wisp\.([a-z_]+)", title)
            if m:
                current = "lua/" + m.group(1)
            elif title == "Screen shape":
                current = "screen"
            else:
                current = "lua"
            sections.setdefault(current, [])
        sections[current].append(line)
    return {k: "".join(v).strip() + "\n" for k, v in sections.items()}


def example_topics(examples):
    """[(topic, text)] for the examples index and each example, sorted by id."""
    out = []
    index = ["# Example scenes\n", "\n",
             "Read one with docs.read(\"example/<id>\").\n", "\n"]
    for d in sorted(p for p in examples.iterdir() if (p / "scene.json").is_file()):
        manifest_text = (d / "scene.json").read_text(encoding="utf-8")
        name = json.loads(manifest_text).get("name", d.name)
        index.append(f"- `{d.name}`: {name}\n")
        parts = [f"# Example: {d.name}\n", "\n", "### scene.json\n", "\n", "```json\n",
                 manifest_text.rstrip("\n") + "\n", "```\n"]
        for lua in sorted(p for p in d.rglob("*.lua") if p.is_file()):
            rel = lua.relative_to(d).as_posix()
            body = lua.read_text(encoding="utf-8")
            parts += ["\n", f"### {rel}\n", "\n", "```lua\n", body.rstrip("\n") + "\n",
                      "```\n"]
        out.append((f"example/{d.name}", "".join(parts)))
    return [("examples", "".join(index))] + out


def generate(doc, examples):
    topics = split_doc(doc.read_text(encoding="utf-8"))
    entries = [("lua", topics.pop("lua"))]
    entries += sorted((k, v) for k, v in topics.items() if k.startswith("lua/"))
    if "screen" in topics:
        entries.append(("screen", topics["screen"]))
    entries += example_topics(examples)
    out = [HEADER]
    for topic, text in entries:
        if END in text:
            raise ValueError(f"{topic}: the text holds {END!r}, which would end the raw string")
        out.append(f'    {{"{topic}", R"{DELIM}({text}){DELIM}"}},\n')
    out.append(FOOTER)
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--doc", type=pathlib.Path, default=ROOT / "docs" / "scene-api.md")
    ap.add_argument("--examples", type=pathlib.Path, default=ROOT / "scenes" / "examples")
    ap.add_argument("--output", type=pathlib.Path,
                    default=ROOT / "components" / "wisp_agent" / "src" / "docs_data.cpp")
    a = ap.parse_args()
    try:
        text = generate(a.doc, a.examples)
    except ValueError as e:
        print(f"gen_agent_docs.py: {e}", file=sys.stderr)
        return 1
    if a.check:
        old = a.output.read_text(encoding="utf-8") if a.output.is_file() else None
        if old != text:
            print(f"{a.output} is stale: run python3 tools/gen_agent_docs.py", file=sys.stderr)
            return 1
        return 0
    a.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
