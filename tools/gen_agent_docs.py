#!/usr/bin/env python3
"""Generates components/wisp_agent/src/docs_data.cpp, the docs.read text
that comes from files (agent-core spec 4.4), stored as raw DEFLATE streams
that docs.cpp inflates when a topic is read:

- docs/scene-api.md, a copy of the schema's schema_markdown() (schema_test's
  DocIsUpToDate keeps it so). docs.cpp cuts the widgets, lua, lua/<module>
  and screen topics from it; the firmware does not carry schema_markdown().
- The examples: scenes/examples/<id>/ gives example/<id>, its scene.json
  then every .lua file by path, and "examples" lists the ids with their
  names. The topics are stored one after another in one stream, with each
  one's offset and size in the table.

Usage: python3 tools/gen_agent_docs.py [--check] [--examples D]
                                       [--scene-api F] [--output F]
--check compares instead of writing and fails when the output is stale. It
inflates the committed streams and compares their text, so it does not
depend on the zlib build that compressed them.
"""

import argparse
import json
import pathlib
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
BYTES_PER_LINE = 16

HEADER = """\
// Generated by tools/gen_agent_docs.py from docs/scene-api.md and
// scenes/examples; do not edit. tools/ci.sh fails when it is stale.

#include "docs_data.hpp"

#include <cstdint>

namespace wisp::agent {

namespace {

// clang-format off
"""

FOOTER = """\
// clang-format on

}}  // namespace

PackedText scene_api_text() {{ return {{kSceneApi, {scene_api_size}}}; }}

PackedText examples_text() {{ return {{kExamples, {examples_size}}}; }}

std::span<const DocEntry> doc_entries() {{ return kDocEntries; }}

}}  // namespace wisp::agent
"""


def example_topics(examples):
    """[(topic, text)] for the examples index and each example, sorted by id."""
    out = []
    index = ["# Example scenes\n", "\n",
             "Read one with docs.read(\"example/<id>\").\n", "\n"]
    for d in sorted(p for p in examples.iterdir() if (p / "scene.json").is_file()):
        manifest_text = (d / "scene.json").read_text(encoding="utf-8")
        name = json.loads(manifest_text).get("name", d.name)
        index.append(f"- `{d.name}`: {name}\n")
        parts = [f"# Example: {d.name}\n", "\n", "### scene.json\n", "\n", "```json\n",
                 manifest_text.rstrip("\n") + "\n", "```\n"]
        for lua in sorted(p for p in d.rglob("*.lua") if p.is_file()):
            rel = lua.relative_to(d).as_posix()
            body = lua.read_text(encoding="utf-8")
            parts += ["\n", f"### {rel}\n", "\n", "```lua\n", body.rstrip("\n") + "\n",
                      "```\n"]
        out.append((f"example/{d.name}", "".join(parts)))
    return [("examples", "".join(index))] + out


def deflate(data):
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    return c.compress(data) + c.flush()


def inflate(data):
    d = zlib.decompressobj(-15)
    out = d.decompress(data) + d.flush()
    if not d.eof or d.unused_data:
        raise ValueError("not one whole raw DEFLATE stream")
    return out


def c_array(name, comment, blob):
    lines = [f"// {comment}\n", f"constexpr uint8_t {name}[] = {{\n"]
    for i in range(0, len(blob), BYTES_PER_LINE):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in blob[i:i + BYTES_PER_LINE]) + "\n")
    lines.append("};\n\n")
    return "".join(lines)


def render(scene_api, entries, scene_api_blob, examples_blob):
    """The file for these texts and their compressed streams."""
    examples = "".join(text for _, text in entries).encode("utf-8")
    out = [HEADER,
           c_array("kSceneApi", "docs/scene-api.md.", scene_api_blob),
           c_array("kExamples", "The example topics below, one after another.", examples_blob),
           "constexpr DocEntry kDocEntries[] = {\n"]
    offset = 0
    for topic, text in entries:
        size = len(text.encode("utf-8"))
        out.append(f'    {{"{topic}", {offset}, {size}}},\n')
        offset += size
    out.append("};\n\n")
    out.append(FOOTER.format(scene_api_size=len(scene_api.encode("utf-8")),
                             examples_size=len(examples)))
    return "".join(out)


def generate(scene_api, entries):
    examples = "".join(text for _, text in entries).encode("utf-8")
    return render(scene_api, entries, deflate(scene_api.encode("utf-8")), deflate(examples))


def read_array(text, name):
    m = re.search(r"constexpr uint8_t " + name + r"\[\] = \{\n(.*?)\n\};", text, re.S)
    if m is None:
        raise ValueError(f"no {name}")
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2}),", m.group(1)))


def read_streams(text):
    """(scene-api text, examples text) inflated from a generated file."""
    return (inflate(read_array(text, "kSceneApi")).decode("utf-8"),
            inflate(read_array(text, "kExamples")).decode("utf-8"))


def check(old, scene_api, entries):
    """True when `old` holds streams that inflate to these texts, in this file layout."""
    try:
        api_blob = read_array(old, "kSceneApi")
        examples_blob = read_array(old, "kExamples")
        if inflate(api_blob).decode("utf-8") != scene_api:
            return False
        if inflate(examples_blob).decode("utf-8") != "".join(t for _, t in entries):
            return False
    except (ValueError, zlib.error, UnicodeDecodeError):
        return False
    return old == render(scene_api, entries, api_blob, examples_blob)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--examples", type=pathlib.Path, default=ROOT / "scenes" / "examples")
    ap.add_argument("--scene-api", type=pathlib.Path, default=ROOT / "docs" / "scene-api.md")
    ap.add_argument("--output", type=pathlib.Path,
                    default=ROOT / "components" / "wisp_agent" / "src" / "docs_data.cpp")
    a = ap.parse_args()
    scene_api = a.scene_api.read_text(encoding="utf-8")
    entries = example_topics(a.examples)
    if a.check:
        old = a.output.read_text(encoding="utf-8") if a.output.is_file() else None
        if old is None or not check(old, scene_api, entries):
            print(f"{a.output} is stale: run python3 tools/gen_agent_docs.py", file=sys.stderr)
            return 1
        return 0
    a.output.write_text(generate(scene_api, entries), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
