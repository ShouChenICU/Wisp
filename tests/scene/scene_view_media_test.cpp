std::shared_ptr<const wisp::core::ScenePackage> package() {
    auto pkg = std::make_shared<wisp::core::ScenePackage>();
    auto add = [&](const char* path, const uint8_t* data, size_t size) {
        auto buf = wisp::os::LargeBuffer::allocate(size);
        std::memcpy(buf.data(), data, size);
        pkg->files.emplace_back(path, std::move(buf));
    };
    add("assets/icon.png", kIconPng, sizeof(kIconPng));
    add("assets/photo.jpg", kBaselineJpeg, sizeof(kBaselineJpeg));
    add("assets/photo.jpeg", kBaselineJpeg, sizeof(kBaselineJpeg));
    add("assets/prog.jpg", kProgressiveJpeg, sizeof(kProgressiveJpeg));
    add("assets/broken.png", kIconPng, 20);
    add("assets/tall.png", kTallPng, sizeof(kTallPng));
    add("assets/wide.png", kWidePng, sizeof(kWidePng));
    add("assets/solid.png", kSolidPng, sizeof(kSolidPng));
    // A baseline JPEG cut short in its scan data.
    add("assets/cut.jpg", kBaselineJpeg, 640);
    return pkg;
}

class SceneViewMedia : public wisp::test::SceneHarness {
protected:
    // The decoded pixels an image shows, or nullptr.
    const lv_image_dsc_t* image_src(wisp::scene::NodeId id) {
        const lv_image_dsc_t* src = nullptr;
        on_ui([&] {
            const void* s = lv_image_get_src(view->object(id));
            if (s != nullptr && lv_image_src_get_type(s) == LV_IMAGE_SRC_VARIABLE)
                src = static_cast<const lv_image_dsc_t*>(s);
        });
        return src;
    }
};

TEST_F(SceneViewMedia, ChartSeriesAndImageFromAssets) {
    start("rect");
    make_vm();
    on_ui([&] { view->set_assets(package()); });
    auto err = open(R"(
        local function series(n)
          local s = {}
          for k = 1, n do
            local points = {}
            for i = 1, 128 do points[i] = (i - 1) * k end
            s[k] = points
          end
          return s
        end
        _G.series = series
        _G.s = state(series(4))
        return ui.screen {
          ui.chart { series = _G.s, min = 0, max = 1000, w = 300, h = 200 },
          ui.chart { type = "bar", series = { { 1, 2, 3 } }, w = 100, h = 100 },
          ui.image { src = "assets/icon.png" },
          ui.image { src = "assets/missing.png" },
          ui.image { src = "assets/broken.png" },
        }
    )");
    ASSERT_FALSE(err) << describe(err);
    on_ui([&] {
        lv_obj_t* chart = view->object(2);
        ASSERT_TRUE(lv_obj_check_type(chart, &lv_chart_class));
        EXPECT_EQ(lv_chart_get_type(chart), LV_CHART_TYPE_LINE);
        EXPECT_EQ(lv_chart_get_point_count(chart), 128u);
        const char* tokens[] = {"accent", "ok", "warn", "danger"};
        lv_chart_series_t* ser = lv_chart_get_series_next(chart, nullptr);
        for (int k = 0; k < 4; ++k) {
            ASSERT_NE(ser, nullptr) << k;
            EXPECT_TRUE(lv_color_eq(lv_chart_get_series_color(chart, ser),
                                    wisp::scene::theme_color(tokens[k])))
                << k;
            // Values between min and max are placed on 0..1000.
            int32_t* y = lv_chart_get_series_y_array(chart, ser);
            EXPECT_EQ(y[100], 100 * (k + 1)) << k;
            ser = lv_chart_get_series_next(chart, ser);
        }
        EXPECT_EQ(ser, nullptr);
        EXPECT_EQ(lv_chart_get_type(view->object(3)), LV_CHART_TYPE_BAR);
        EXPECT_EQ(lv_chart_get_point_count(view->object(3)), 3u);
    });

    // A fifth series is the scene's error, at the chart's line.
    err = message("_G.s:set(_G.series(5))");
    ASSERT_TRUE(err);
    EXPECT_EQ(err->text(),
              "main.lua:14: ui.chart: property 'series' expects a table of up to 4 tables of up "
              "to 128 numbers");

    const lv_image_dsc_t* icon = image_src(4);
    ASSERT_NE(icon, nullptr);
    EXPECT_EQ(icon->header.w, 6u);
    EXPECT_EQ(icon->header.h, 4u);
    EXPECT_EQ(image_src(5), nullptr);
    EXPECT_EQ(image_src(6), nullptr);
    auto warnings = take_warnings();
    ASSERT_EQ(warnings.size(), 2u);
    EXPECT_EQ(warnings[0], "ui.image: no asset 'assets/missing.png'");
    EXPECT_EQ(warnings[1], "ui.image: cannot decode 'assets/broken.png'");
}

