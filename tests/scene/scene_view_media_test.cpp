TEST_F(SceneViewMedia, ImagesAndCanvasesShareTheViewBudget) {
    static_assert(wisp::scene::SceneView::kMaxMediaBytes == 4u * 1024 * 1024);
    start("rect");
    make_vm();
    on_ui([&] { view->set_assets(package()); });
    // 300x300 ARGB8888 is 360,000 bytes and each 700x700 RGB565 canvas
    // 980,000: the fourth canvas does not fit in 4 MB.
    const char* scene = R"(
        _G.w = state(%d)
        local function fill(g) g:fill("#FF0000") end
        return ui.screen {
          ui.image { src = "assets/solid.png" },
          ui.canvas { w = 700, h = 700, draw = fill },
          ui.canvas { w = 700, h = 700, draw = fill },
          ui.canvas { w = 700, h = 700, draw = fill },
          ui.canvas { w = _G.w, h = 700, draw = fill },
        }
    )";
    auto canvas_src = [&](wisp::scene::NodeId id) {
        const void* src = nullptr;
        on_ui([&] {
            lv_obj_update_layout(view->screen());  // a new size redraws
            src = lv_image_get_src(view->object(id));
        });
        return src;
    };
    char text[512];
    std::snprintf(text, sizeof(text), scene, 700);
    auto err = open(text);
    ASSERT_FALSE(err) << describe(err);
    ASSERT_NE(image_src(2), nullptr);
    for (wisp::scene::NodeId id : {3u, 4u, 5u}) EXPECT_NE(canvas_src(id), nullptr) << id;
    EXPECT_EQ(canvas_src(6), nullptr);
    auto warnings = take_warnings();
    ASSERT_EQ(warnings.size(), 1u);
    EXPECT_EQ(warnings[0], "ui.canvas: too large");

    // Shrunk, it fits.
    err = message("_G.w:set(100)");
    ASSERT_FALSE(err) << describe(err);
    EXPECT_NE(canvas_src(6), nullptr);
    EXPECT_TRUE(take_warnings().empty());

    // A new tree starts from what the old one released.
    vm.reset();
    batch.clear();
    next_id = 1;
    std::snprintf(text, sizeof(text), scene, 100);
    err = open(text);
    ASSERT_FALSE(err) << describe(err);
    ASSERT_NE(image_src(2), nullptr);
    for (wisp::scene::NodeId id : {3u, 4u, 5u, 6u}) EXPECT_NE(canvas_src(id), nullptr) << id;
    EXPECT_TRUE(take_warnings().empty());
}

