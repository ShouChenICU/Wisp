TEST_F(SceneViewMedia, JpegFromAssets) {
    wisp::ui::UiConfig config;
    config.install_image_decoders = wisp::port::sim::install_image_decoders;
    start("rect", false, config);
    make_vm();
    on_ui([&] { view->set_assets(package()); });
    auto err = open(R"(
        return ui.screen {
          ui.image { src = "assets/photo.jpg" },
          ui.image { src = "assets/photo.jpeg" },
          ui.image { src = "assets/prog.jpg" },
        }
    )");
    ASSERT_FALSE(err) << describe(err);
    for (wisp::scene::NodeId id : {2u, 3u}) {
        const lv_image_dsc_t* photo = image_src(id);
        ASSERT_NE(photo, nullptr);
        EXPECT_EQ(photo->header.w, 20u);
        EXPECT_EQ(photo->header.h, 12u);
        // Decoded straight into the display's format.
        EXPECT_EQ(photo->header.cf, LV_COLOR_FORMAT_RGB565);
        uint16_t left = 0, right = 0;
        std::memcpy(&left, photo->data + 6 * photo->header.stride + 2 * 2, 2);
        std::memcpy(&right, photo->data + 6 * photo->header.stride + 17 * 2, 2);
        EXPECT_GE(left >> 11, 28) << "left half is red";
        EXPECT_LE(left & 0x1F, 3);
        EXPECT_GE(right & 0x1F, 28) << "right half is blue";
        EXPECT_LE(right >> 11, 3);
    }
    EXPECT_EQ(image_src(4), nullptr);
    auto warnings = take_warnings();
    ASSERT_EQ(warnings.size(), 1u);
    EXPECT_EQ(warnings[0], "ui.image: unsupported JPEG 'assets/prog.jpg'");

    // The schema takes .jpg and .jpeg, and nothing else.
    vm.reset();
    batch.clear();
    err = open("return ui.screen { ui.image { src = 'assets/a.gif' } }");
    ASSERT_TRUE(err);
    EXPECT_EQ(err->text(),
              "main.lua:1: ui.image: property 'src' expects a path assets/<name>.png, .jpg or "
              ".jpeg, got 'assets/a.gif'");
}

